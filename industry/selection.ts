// 精选的门槛。评分标准本身写在 prompts/selection-score.md；这里只决定“多少分算入选”。
// 每篇资料由评分模型独立打两次分（0–100），两次之和 ≥ 2 × 门槛才进精选，卡片上显示两次的平均分。
// 门槛按信源分级区分：厂商官方一手的门槛低一些，行业媒体和个人的高一些。
//
// ── 这组数是在本站真实数据上校准出来的，不是沿用 AI 行业的默认值 ──────────────
// AI 行业默认（T1 60 / T1_5 65 / T2 76）直接搬到安防行业会一条都选不出来：安防行业
// 内容偏“事实公告”，分数整体比 AI 行业低 15–20 分（实测 T1 官方源最高只有 58 分、均值 29）。
// 沿用默认值等于日报永远空白，所以按下面两步重新定了门槛：
//
//   1) 锚点：AI 站在它自己的默认门槛下，T1 与 T2 的入选率都约为 22%（实测 T1 4/18、T2 9/41）。
//      把“约 20% 入选率”作为本站要保持的严度，而不是照搬分数。
//   2) 门槛扫描（本站 43 条已评分样本）：
//        T1 门槛 40 → 入选 5/25 = 20%   （60 → 0/25 = 0%，不可用）
//        T2 门槛 56 → 入选 5/23 = 22%   （76 → 2/23 = 9%）
//      偏移量沿用原结构的 +5 / +16，得到 T1_5 = 45。
//   3) 人工核对：门槛线上留下的是 Axis 新品发布、同方威视机场 300 台套部署、
//      《网络安全标识管理办法》发布（76）、公安部废止 119 项行标（76）；
//      门槛线淘汰的是战略合作签约、领导来访调研、企业获奖、论坛出席——
//      与 prompts/selection-score.md 里「必须压住的噪声」一致，说明是门槛偏高而非评分跑偏。
//
// 样本量仍小（几十条）。请按 docs/selection.md 积累 100–200 条自己标注的 .data/gold.jsonl，
// 用 scripts/eval-selection.ts 重跑（含 development/holdout 拆分与门槛扫描），再据此微调。
// 改了门槛或评分提示词都要重新校准，不要凭感觉改数字。

